/* Blending two RGB565 colours by averaging their stored values averages
 * gamma-encoded numbers, which is not what light does. The visible result
 * is antialiased text that blooms when it is light on dark and goes thin
 * when it is dark on light - the same glyph, two different weights,
 * depending only on the background it landed on.
 *
 * These tables take each channel to linear light at 12 bits, blend there,
 * and come back. Cost is six lookups per pixel instead of one packed
 * multiply, paid only on glyph and alpha-image pixels. ROM cost is 2.2 KiB.
 *
 * lin5/lin6:     5- or 6-bit channel -> 0..4095 linear
 * delin5/delin6: linear rounded to quarters (0..1024) -> 5- or 6-bit
 *                channel. Quarters rather than whole linear values so the
 *                reverse tables stay small; rounded rather than truncated
 *                so the darkest codes survive the round trip.
 */


/* a is transparency in 0..15, exactly as the font alpha format counts it:
 * a == 0 keeps c2 entirely, a == 15 keeps c1. Same signature and the same
 * sense as blend_two_colors(), so it can stand in for it. */
static inline unsigned lcd_blend_two_colors_gamma(unsigned c1, unsigned c2,
                                                  unsigned a)
{
    /* Stretch 0..15 to 0..16 the way blend_two_colors() does, so full
     * alpha really is full. The two endpoints return the input colour
     * untouched rather than through the tables: twelve bits of linear
     * light cannot tell green code 1 from code 0, and a glyph is mostly
     * endpoints anyway, so this is both exact and the fast path. */
    unsigned w1, w2, r, g, b;

    if (a == 0)
        return c2;
    if (a >= 15)
        return c1;

    w1 = a + (a >> 3);
    w2 = 16 - w1;

    /* sum is linear x16; +32 rounds rather than truncates, which is what
     * keeps the darkest codes from collapsing to zero on the way back */
    r = delin5[(lin5[(c1 >> 11) & 0x1f] * w1 +
                lin5[(c2 >> 11) & 0x1f] * w2 + 32) >> 6];
    g = delin6[(lin6[(c1 >>  5) & 0x3f] * w1 +
                lin6[(c2 >>  5) & 0x3f] * w2 + 32) >> 6];
    b = delin5[(lin5[ c1        & 0x1f] * w1 +
                lin5[ c2        & 0x1f] * w2 + 32) >> 6];

    return (r << 11) | (g << 5) | b;
}

